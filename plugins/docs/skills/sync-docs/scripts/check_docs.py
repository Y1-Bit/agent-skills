#!/usr/bin/env python3
"""Deterministic drift checks for a project's Markdown docs. Python 3.9+ stdlib only.

Usage: check_docs.py [root]
Prints `path:line: LEVEL kind: message` per finding and a summary.
Exit code 1 if any `error` finding (2 if root is missing), so it can run in a check command.
"""

import io
import json
import os
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import unquote

SKIP_DIRS = {".git", "node_modules", "dist", "build", "vendor", ".venv", "venv", "__pycache__", ".next", "target"}
LOCKFILES = {"package-lock.json", "pnpm-lock.yaml", "yarn.lock", "bun.lockb", "uv.lock", "poetry.lock", "Cargo.lock"}
DOC_EXT = (".md", ".mdx")
FILE_EXT = re.compile(
    r"\.(md|mdx|ts|tsx|js|jsx|mjs|cjs|json|jsonc|py|toml|ya?ml|sh|css|scss|html|txt|sql|go|rs|rb|java|kt|swift"
    r"|cfg|ini|svg|png|jpe?g|webp|gif|lock|env|example)$"
)
RECORD_NAME = re.compile(
    r"-(RESULT|REPORT|AUDIT)S?\b|^(CHANGELOG|CHANGES|HISTORY|NEWS|RELEASES?)\b|release-notes|\d{4}-\d{2}-\d{2}", re.I
)
RECORD_DIRS = {"adr", "adrs", "decisions", "rfc", "rfcs"}
GENERATED = re.compile(r"auto-?generated|do not edit|this file (is|was) generated|generated by", re.I)
# A block another tool rewrites, e.g. <!-- TOOL:BEGIN --> ... <!-- TOOL:END --> or <!-- BEGIN_X -->.
MANAGED_BEGIN = re.compile(r"<!--\s*(?:[\w.-]+[:_ -])?(?:BEGIN|START)(?:[:_ -][\w.-]+)?\s*-->")
MANAGED_END = re.compile(r"<!--\s*(?:[\w.-]+[:_ -])?END(?:[:_ -][\w.-]+)?\s*-->")
FENCE = re.compile(r"^\s{0,3}(`{3,}|~{3,})")
CODE_SPAN = re.compile(r"(`+)(.+?)\1")
LINK = re.compile(r"!?\[[^\]]*\]\(\s*<?([^)\s>]+)>?(?:\s+[\"'][^)]*)?\)")
REF_LINK = re.compile(r"^\s*\[(?!\^)[^\]]+\]:\s*<?(\S+?)>?(?:\s|$)")
HTML_ANCHOR = re.compile(r"<a\s[^>]*(?:name|id)=[\"']([^\"']+)[\"']", re.I)
SCHEME = re.compile(r"^([a-z][a-z0-9+.-]*:|//)", re.I)
# A script name never starts with "-", so `npm run -w pkg build` is left unchecked.
PKG_SCRIPT = re.compile(r"\b(?:npm|pnpm|yarn|bun)\s+run\s+([\w:.][\w:.-]*)|\bnpm\s+(test|start)\b")
MAKE_TARGET = re.compile(r"\bmake\s+(?:-[Cf]\s*\S+\s+|-\S+\s+|\w+=\S*\s+)*([A-Za-z][\w.-]*)")
MAKEFILE_RULE = re.compile(r"^([A-Za-z][\w.-]*(?:[ \t]+[A-Za-z][\w.-]*)*)[ \t]*:(?!=)", re.M)
ENV_NAME = re.compile(r"^\$?\{?([A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+)\}?(?:=.*)?$")
IDENT_CHAIN = re.compile(r"^[A-Za-z_$][\w$]*(?:\.[A-Za-z_$][\w$]*)*$")
TOKEN = re.compile(r"[A-Za-z_$][\w$]*")
STALE = re.compile(r"\b(TODO|TBD|FIXME|WIP)\b|coming soon", re.I)
NODE_VER = re.compile(r"\bNode(?:\.js)?\s*(?:v|>=?\s*)?(\d{2})\b")
PY_VER = re.compile(r"\bPython\s*(?:>=?\s*)?(3\.\d+)\b")
IGNORE_LINE = re.compile(r"<!--\s*check-docs:\s*ignore\s*-->")
IGNORE_FILE = re.compile(r"<!--\s*check-docs:\s*ignore-file\b([^>]*?)-->")


class Repo:
    def __init__(self, root):
        self.root = root.resolve()
        self.files = self._list_files()
        self.docs = sorted(f for f in self.files if f.endswith(DOC_EXT))
        self.suffixes = path_suffixes(self.files)
        self.classes = {d: self._classify(d) for d in self.docs}
        self.tokens = self._code_tokens()
        self.pkg_scripts, self.has_pkg = self._package_scripts()
        self.make_targets = self._make_targets()
        self.heading_cache = {}

    def _list_files(self):
        try:
            out = subprocess.run(
                ["git", "-C", str(self.root), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
                capture_output=True, check=True,
            ).stdout.decode("utf-8", "surrogateescape")
            names = out.split("\0")
        except (OSError, subprocess.CalledProcessError):
            names = []
            for dirpath, dirnames, filenames in os.walk(self.root):
                dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
                rel = Path(dirpath).relative_to(self.root)
                names += [(rel / f).as_posix() for f in filenames]
        # is_file() drops broken symlinks, sockets and FIFOs (reading a FIFO would hang)
        return [f for f in names if f and (self.root / f).is_file()]

    def read(self, rel):
        try:
            data = (self.root / rel).read_bytes()
        except OSError:
            return ""
        return "" if b"\0" in data[:1024] else data.decode("utf-8", "replace")

    def _classify(self, doc):
        lines = self.read(doc).splitlines()
        head = "\n".join(lines[:5])
        # only an HTML comment near the top or the first line, so "do not edit `gen/`" in a rule list does not count
        marker = " ".join(re.findall(r"<!--(.*?)-->", head, re.S)) + "\n" + (lines[0] if lines else "")
        if GENERATED.search(marker):
            return "generated"
        p = Path(doc)
        if RECORD_NAME.search(p.name) or RECORD_DIRS & {part.lower() for part in p.parts[:-1]}:
            return "record"
        return "living"

    def _code_tokens(self):
        tokens = set()
        for f in self.files:
            if f.endswith(DOC_EXT) or Path(f).name in LOCKFILES:
                continue
            if (self.root / f).stat().st_size <= 1_000_000:
                tokens.update(TOKEN.findall(self.read(f)))
        return tokens

    def _package_scripts(self):
        scripts, found = set(), False
        for f in self.files:
            if Path(f).name == "package.json":
                found = True
                try:
                    scripts.update(json.loads(self.read(f)).get("scripts", {}))
                except (ValueError, AttributeError):
                    pass
        return scripts, found

    def _make_targets(self):
        makefiles = [f for f in self.files if Path(f).name in {"Makefile", "makefile", "GNUmakefile"} or f.endswith(".mk")]
        if not makefiles:
            return None
        return {t for f in makefiles for head in MAKEFILE_RULE.findall(self.read(f)) for t in head.split()}

    def anchors(self, doc):
        if doc not in self.heading_cache:
            found, seen, prev = set(), {}, ""
            for _, line, in_fence in lines_of(self.read(doc)):
                if in_fence:
                    prev = ""
                    continue
                found.update(a.lower() for a in HTML_ANCHOR.findall(line))
                atx = re.match(r"^\s{0,3}#{1,6}\s+(.*?)\s*#*\s*$", line)
                setext = prev.strip() and not prev.lstrip().startswith(("-", "*", "+", ">", "|")) and re.match(r"^\s{0,3}(=+|-+)\s*$", line)
                title = atx.group(1) if atx else (prev.strip() if setext else None)
                if title is not None:
                    base = slug(title)
                    n = seen.get(base, 0)
                    seen[base] = n + 1
                    found.add(base if n == 0 else f"{base}-{n}")
                prev = line
            self.heading_cache[doc] = found
        return self.heading_cache[doc]

    def declared_versions(self):
        node = py = None
        for name in (".nvmrc", ".node-version"):
            m = re.search(r"(\d+)", self.read(name))
            node = node or (m and m.group(1))
        try:
            engines = json.loads(self.read("package.json") or "{}").get("engines", {}).get("node", "")
            m = re.search(r"(\d+)", engines)
            node = node or (m and m.group(1))
        except (ValueError, AttributeError):
            pass
        m = re.search(r"(3\.\d+)", self.read(".python-version"))
        py = m and m.group(1)
        m = re.search(r"requires-python\s*=\s*[\"'][^\"']*?(3\.\d+)", self.read("pyproject.toml"))
        py = py or (m and m.group(1))
        return node, py


def path_suffixes(files):
    """Every trailing run of path segments of every file and folder, for O(1) 'some path ends with X'."""
    out = set()
    for f in files:
        parts = f.split("/")
        for end in range(1, len(parts) + 1):
            for start in range(end):
                out.add("/".join(parts[start:end]))
    return out


def slug(text):
    """GitHub-style heading anchor."""
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"<[^>]+>", "", text)
    return re.sub(r"[^\w\- ]", "", text.strip().lower()).replace(" ", "-")


def lines_of(text):
    """Yield (line_no, line, in_fence) for every line but fence delimiters, skipping front matter.

    A fence line is yielded with in_fence=None so callers can see where a block opens.
    """
    lines = text.splitlines()
    start = 0
    if lines and lines[0].strip() == "---":
        end = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
        start = end + 1 if end else 0
    fence = None
    for i in range(start, len(lines)):
        line = lines[i]
        m = FENCE.match(line)
        if m and fence is None:
            fence = m.group(1)
            yield i + 1, line, None
            continue
        if m and fence and m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence) and not line[m.end():].strip():
            fence = None
            continue
        yield i + 1, line, fence is not None


def is_repo_path(token, repo, doc_dir):
    """A backticked token worth checking as a path: known extension, or first segment exists."""
    if not token or token.startswith(("/", "~")) or FILE_EXT.fullmatch(token) or SCHEME.match(token):
        return False
    if re.search(r"[\s<>{}*?$|\[\]]|\.\.\.", token):
        return False
    first = token.split("/")[0]
    return bool(FILE_EXT.search(token)) or (
        "/" in token and ((repo.root / first).exists() or (repo.root / doc_dir / first).exists())
    )


def path_exists(rel, repo, doc_dir):
    """Exists from the root or the doc's folder, or some repo path ends with it (docs name paths
    relative to a sub-package, or bare file names)."""
    rel = rel.removeprefix("./")
    return (repo.root / rel).exists() or (repo.root / doc_dir / rel).exists() or rel in repo.suffixes


def check_doc(doc, repo, node_ver, py_ver):
    findings = []
    cls = repo.classes[doc]
    doc_dir = Path(doc).parent
    ignored_lines, file_kinds = set(), []
    managed = ignore_block = False
    prev_prose = ""

    def add(line_no, level, kind, msg):
        # records are never edited, so their findings must not fail a gate
        findings.append((doc, line_no, "warn" if cls == "record" and level == "error" else level, kind, msg))

    for n, line, in_fence in lines_of(repo.read(doc)):
        if in_fence is None:  # fence opens; a marker on the line just before ignores the whole block
            ignore_block = bool(IGNORE_LINE.search(prev_prose))
            continue
        if in_fence:
            if ignore_block or managed or cls != "living" or line.lstrip().startswith("#"):
                continue
            check_scripts(line, repo, lambda lvl, kind, msg: add(n, lvl, kind, msg))
            continue

        prose = CODE_SPAN.sub("", line)  # markers shown in backticks are documentation, not markers
        prev_prose = prose
        file_kinds += [m.group(1).split() for m in IGNORE_FILE.finditer(prose)]
        if IGNORE_LINE.search(prose):
            ignored_lines.add(n)
        if MANAGED_BEGIN.search(prose):
            managed = True
        if MANAGED_END.search(prose):
            managed = False
            continue
        if managed:
            continue

        for target in LINK.findall(prose) + REF_LINK.findall(prose):
            check_link(target, doc, doc_dir, repo, lambda lvl, kind, msg: add(n, lvl, kind, msg))

        if cls != "living":
            continue

        spans = [m.group(2).strip() for m in CODE_SPAN.finditer(line)]
        for span in spans:
            check_scripts(span, repo, lambda lvl, kind, msg: add(n, lvl, kind, msg))
            check_span(span, repo, doc_dir, lambda lvl, kind, msg: add(n, lvl, kind, msg))

        if STALE.search(prose):
            add(n, "info", "stale", line.strip()[:100])
        for pattern, declared, label in ((NODE_VER, node_ver, "Node"), (PY_VER, py_ver, "Python")):
            for ver in pattern.findall(line):
                if declared and ver != declared:
                    add(n, "warn", "version", f"{label} {ver} in text, project declares {declared}")

    return [
        f for f in findings
        if f[1] not in ignored_lines and not any(not kinds or f[3] in kinds for kinds in file_kinds)
    ]


def check_scripts(code, repo, add):
    for a, b in PKG_SCRIPT.findall(code):
        name = a or b
        if not repo.has_pkg:
            add("warn", "script", f"`{name}`: no package.json in the repo")
        elif name not in repo.pkg_scripts:
            add("error", "script", f"package script `{name}` not found in any package.json")
    if repo.make_targets is not None:
        for target in MAKE_TARGET.findall(code):
            if target not in repo.make_targets:
                add("error", "script", f"make target `{target}` not found in any Makefile")


def check_span(span, repo, doc_dir, add):
    token = re.sub(r":\d+(?::\d+)?$", "", span).rstrip("/")  # drop a `file:line` suffix
    if is_repo_path(token, repo, doc_dir):
        if not path_exists(token, repo, doc_dir):
            # a bare name may be a file the reader creates or an ignored local file
            add("error" if "/" in token else "warn", "path", f"`{token}` does not exist")
        return
    env = ENV_NAME.match(span)
    if env:
        if env.group(1) not in repo.tokens:
            add("warn", "env", f"`{env.group(1)}` not found in code or config")
        return
    ident = re.sub(r"\(.*\)$", "", span)
    if IDENT_CHAIN.match(ident) and looks_like_code(span, ident) and ident.split(".")[-1] not in repo.tokens:
        add("warn", "symbol", f"`{ident}` not found in code")


def looks_like_code(span, ident):
    return (
        span.endswith(")")
        or "." in ident
        or re.search(r"[a-z][A-Z]", ident) is not None
        or re.search(r"[a-z0-9]_[a-z0-9]", ident) is not None
    )


def check_link(target, doc, doc_dir, repo, add):
    if SCHEME.match(target):
        return
    path_part, _, anchor = target.partition("#")
    path_part = unquote(path_part.split("?")[0])
    if path_part:
        rel = Path(path_part.lstrip("/")) if path_part.startswith("/") else doc_dir / path_part
        resolved = Path(os.path.normpath(rel)).as_posix()
        if not (repo.root / resolved).exists():
            add("error", "link", f"`{target}` -> {resolved} does not exist")
            return
    else:
        resolved = doc
    if anchor and resolved.endswith(DOC_EXT) and unquote(anchor).lower() not in repo.anchors(resolved):
        add("error", "anchor", f"`#{anchor}` is not a heading in {resolved}")
    if repo.classes.get(doc) == "living" and repo.classes.get(resolved) == "record":
        add("info", "record-cited", f"links the dated record {resolved}; make sure it is not cited as current truth")


def main(argv):
    root = Path(argv[1] if len(argv) > 1 else ".")
    if not root.is_dir():
        print(f"check_docs: {root} is not a directory", file=sys.stderr)
        return 2
    if isinstance(sys.stdout, io.TextIOWrapper):  # a cp1252 console must not crash on a non-ASCII path
        sys.stdout.reconfigure(errors="replace")
    repo = Repo(root)
    node_ver, py_ver = repo.declared_versions()
    for cls in ("living", "record", "generated"):
        docs = [d for d in repo.docs if repo.classes[d] == cls]
        print(f"# {cls} ({len(docs)}): {', '.join(docs) or '-'}")
    findings = [f for d in repo.docs if repo.classes[d] != "generated" for f in check_doc(d, repo, node_ver, py_ver)]
    for doc, n, level, kind, msg in findings:
        print(f"{doc}:{n}: {level} {kind}: {msg}")
    counts = {lvl: sum(f[2] == lvl for f in findings) for lvl in ("error", "warn", "info")}
    print(f"# {counts['error']} errors, {counts['warn']} warnings, {counts['info']} info in {len(repo.docs)} docs")
    return 1 if counts["error"] else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
