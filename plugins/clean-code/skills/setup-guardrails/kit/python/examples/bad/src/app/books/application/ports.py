"""Typical agent output: one port that every use case reads a different slice of."""

from typing import Protocol


class BookStore(Protocol):
    async def load(self) -> None: ...
    async def reload(self) -> None: ...
    async def find_by_id(self, book_id: str) -> str | None: ...
    async def search(self, query: str) -> list[str]: ...
    async def catalog(self, title: str) -> None: ...
    async def withdraw(self, book_id: str) -> None: ...
    async def rename(self, book_id: str, title: str) -> None: ...
    def export_csv(self) -> str: ...
    def subscribe(self, listener: object) -> None: ...
    def reset(self) -> None: ...
    def format_for_list(self, book_id: str) -> str: ...
